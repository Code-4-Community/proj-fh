/**
 * Number of resources seeded for each review status and category pair.
 * 5 statuses x 2 categories x 3 = 30 resources.
 */
const RESOURCES_PER_GROUP = 3;

/**
 * The categories that get seeded. OTHER is intentionally left out.
 */
type SeededCategory = Category.FOOD_ACCESS | Category.HOUSING;

/**
 * The order categories are seeded in within each review status.
 */
const SEEDED_CATEGORIES: SeededCategory[] = [
  Category.FOOD_ACCESS,
  Category.HOUSING,
];

/**
 * A resource row ready to insert. Built from the entity so that leaving out a
 * required column is a compile error. The omitted columns are generated by the
 * database.
 */
type NewResource = Omit<Resource, 'resource_id' | 'created_at' | 'updated_at'>;

/**
 * Usable tags grouped by "category:group", in tag_id order.
 */
type TagLookup = Map<string, Tag[]>;

/**
 * Identifies one seeded resource.
 */
interface ResourceSlot {
  status: ReviewStatus;
  category: SeededCategory;
  /** Position within this status and category, from 1 to RESOURCES_PER_GROUP. */
  numberInGroup: number;
  /** Position across all seeded resources, starting at 0. Used for unique names and contact details. */
  index: number;
  /** Position among seeded resources of the same category, starting at 0. Used to rotate sample details. */
  categoryIndex: number;
}
/**
 * The review values shared by every seeded resource in one review status.
 * Keeping them per status makes each status look realistic in the review
 * queue, for example rejected resources have low scores and rejection notes.
 */
interface StatusProfile {
  /** Short status name used in program names, e.g. "Food Program Rejected 2". */
  label: string;
  /** Score.overall_rating, from 1 to 5. */
  overallRating: number;
  /** Resource.responsiveness, from 1 to 5. */
  responsiveness: number;
  responseTime: ResponseTime;
  recommendation: Recommendation;
  referralRealistic: YesNoMaybe;
  canReferDirectly: boolean;
  providesFollowup: boolean;
  /** How many months before today last_verified_date is set. */
  monthsSinceVerified: number;
  interactionNotes: string;
  strengths: string;
  redFlagConcerns: string;
  referralNotes: string;
  followupNeeded: string;
  /** Common tag groups to pick from, one tag per group. */
  commonTagGroups: TagGroup[];
  needsChangesNotes?: string;
  submissionRejectionNotes?: string;
}

/**
 * The values shared by every seeded resource in one category.
 */
interface CategoryTemplate {
  /** Word used in program names, e.g. "Housing Program Archived 3". */
  label: string;
  /** Used in organization names, e.g. "Sample Housing Network 12". */
  organizationLabel: string;
  tagCategory: TagCategory;
  /** One tag is picked per group, in order. A group listed twice gets two different tags. */
  categoryTagGroups: TagGroup[];
  eligibility: string;
  accessibilityNotes: string;
  programNotes: string;
}

