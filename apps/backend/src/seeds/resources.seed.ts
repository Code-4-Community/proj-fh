/**
 * Returns the item at index, wrapping around the end of the list, so sample
 * details rotate across resources without any randomness.
 */
function rotate<T>(items: readonly T[], index: number): T {
  const item = items[index % items.length];
  if (item === undefined) {
    throw new Error('Cannot rotate through an empty list.');
  }
  return item;
}

/**
 * Returns today's date moved back by the given number of months.
 */
function monthsAgo(months: number): Date {
  const date = new Date();
  date.setMonth(date.getMonth() - months);
  return date;
}

/**
 * Returns a copy of date moved back by the given number of days.
 */
function daysBefore(date: Date, days: number): Date {
  const result = new Date(date);
  result.setDate(result.getDate() - days);
  return result;
}

/**
 * Builds the TagLookup key for a tag category and group.
 */
function tagKey(category: TagCategory, group: TagGroup): string {
  return `${category}:${group}`;
}

/**
 * Loads every tag a seeded resource may use, grouped by category and group.
 * Custom and free-text tags are skipped because they expect typed-in text.
 */
async function loadTagLookup(manager: EntityManager): Promise<TagLookup> {
  const tags = await manager.find(Tag, {
    where: { is_custom: false, allows_free_text: false },
    order: { tag_id: 'ASC' },
  });

  const lookup: TagLookup = new Map();
  for (const tag of tags) {
    const key = tagKey(tag.category, tag.group);
    const group = lookup.get(key) ?? [];
    group.push(tag);
    lookup.set(key, group);
  }
  return lookup;
}

/**
 * Picks a resource's tag IDs: one per category tag group from its category
 * template, then one per common tag group from its status profile. When a group
 * is listed twice, each pick moves one tag further along, so the tags differ.
 */
function pickTags(lookup: TagLookup, slot: ResourceSlot): number[] {
  const template = CATEGORY_TEMPLATES[slot.category];
  const profile = STATUS_PROFILES[slot.status];

  const picks = [
    ...template.categoryTagGroups.map((group) => ({
      category: template.tagCategory,
      group,
    })),
    ...profile.commonTagGroups.map((group) => ({
      category: TagCategory.COMMON,
      group,
    })),
  ];

  const timesUsedByKey = new Map<string, number>();
  return picks.map(({ category, group }) => {
    const key = tagKey(category, group);
    const options = lookup.get(key);
    if (!options || options.length === 0) {
      throw new Error(
        `No usable tags for category "${category}" and group "${group}". Have the migrations been run?`,
      );
    }

    const timesUsed = timesUsedByKey.get(key) ?? 0;
    timesUsedByKey.set(key, timesUsed + 1);
    return rotate(options, slot.categoryIndex + timesUsed).tag_id;
  });
}

/**
 * Builds the full resource row for one slot.
 */
function buildResource(
  slot: ResourceSlot,
  scoreId: number,
  tagIds: number[],
): NewResource {
  const profile = STATUS_PROFILES[slot.status];
  const template = CATEGORY_TEMPLATES[slot.category];
  const location = rotate(LOCATIONS, slot.categoryIndex);
  const contact = rotate(STAFF_CONTACTS, slot.categoryIndex);

  const slug = `${template.label} ${profile.label} ${slot.numberInGroup}`
    .toLowerCase()
    .replace(/\s+/g, '-');
  const email = `${slug}@example.org`;
  const lastVerifiedDate = monthsAgo(profile.monthsSinceVerified);

  return {
    score_id: scoreId,
    organization_name: `Sample ${template.organizationLabel} ${slot.index + 1}`,
    program_name: `${template.label} Program ${profile.label} ${slot.numberInGroup}`,
    category: slot.category,
    address: `${100 + slot.index} ${location.street}, ${location.city}, MA ${location.zipCode}`,
    county: location.county,
    zip_code: location.zipCode,
    phone: `(617) 555-${String(100 + slot.index).padStart(4, '0')}`,
    email,
    website: `https://example.org/${slug}`,
    public_fields: rotate(PUBLIC_FIELD_SETS, slot.categoryIndex),
    eligibility: template.eligibility,
    review_status: slot.status,
    last_verified_date: lastVerifiedDate,
    completed_by: rotate(COMPLETED_BY_NAMES, slot.categoryIndex),
    outreach_date: daysBefore(lastVerifiedDate, 7),
    staff_contact_name: contact.name,
    staff_contact_role: contact.role,
    responsiveness: profile.responsiveness,
    response_time: profile.responseTime,
    interaction_notes: profile.interactionNotes,
    accessibility_notes: template.accessibilityNotes,
    program_notes: template.programNotes,
    red_flag_concerns: profile.redFlagConcerns,
    can_refer_directly: profile.canReferDirectly,
    has_referral_contact: profile.canReferDirectly,
    referral_contact: profile.canReferDirectly ? email : undefined,
    provides_followup: profile.providesFollowup,
    referral_realistic: profile.referralRealistic,
    referral_notes: profile.referralNotes,
    recommendation: profile.recommendation,
    strengths: profile.strengths,
    followup_needed: profile.followupNeeded,
    needs_changes_notes: profile.needsChangesNotes,
    submission_rejection_notes: profile.submissionRejectionNotes,
    tags: tagIds,
  };
}

/**
 * Replaces all resources and scores with RESOURCES_PER_GROUP resources for
 * every review status and seeded category. Each resource gets its own score,
 * created first so its generated score_id can be stored on the resource.
 *
 * Tags are only read, never modified. They come from migrations.
 *
 * @returns The number of resources inserted.
 */
export async function seedResources(manager: EntityManager): Promise<number> {
  await manager.query('TRUNCATE TABLE resources, scores RESTART IDENTITY');
  const tagLookup = await loadTagLookup(manager);

  let index = 0;
  for (const [statusIndex, status] of Object.values(ReviewStatus).entries()) {
    for (const category of SEEDED_CATEGORIES) {
      for (
        let numberInGroup = 1;
        numberInGroup <= RESOURCES_PER_GROUP;
        numberInGroup++
      ) {
        const categoryIndex =
          statusIndex * RESOURCES_PER_GROUP + (numberInGroup - 1);
        const slot: ResourceSlot = {
          status,
          category,
          numberInGroup,
          index,
          categoryIndex,
        };

        const score = await manager.save(
          Score,
          manager.create(Score, {
            overall_rating: STATUS_PROFILES[status].overallRating,
          }),
        );
        const tagIds = pickTags(tagLookup, slot);
        await manager.save(
          Resource,
          manager.create(Resource, buildResource(slot, score.score_id, tagIds)),
        );

        index++;
      }
    }
  }

  return index;
}
