import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  Unique,
} from 'typeorm';
import { TagGroup } from './tag-group.entity';
import { TagCategory } from './types';

/**
 * Represents a Tag in the system.
 * A Tag is one selectable answer option (or one Yes/Unsure answer) on a vetting form.
 * Resources store the IDs of their Tags in Resource.tags.
 */
@Entity()
@Unique('UQ_tags_group_id_slug', ['group_id', 'slug'])
@Check('CHK_tags_other_text', '("other_text" IS NOT NULL) = "is_custom"')
@Index('IDX_tags_category', ['category'])
export class Tag {
  /**
   * Unique ID of a Tag, generated by the database.
   *
   * E.g. 1, 2, 3, 4, 5
   */
  @PrimaryGeneratedColumn({
    type: 'int',
    primaryKeyConstraintName: 'PK_tags_tag_id',
  })
  tag_id!: number;

  /**
   * Which resources the Tag applies to: one resource category, or 'common' for every resource.
   * A Tag can only be attached to a Resource whose category is equal to it or when it is 'common'.
   *
   * E.g. TagCategory.COMMON, TagCategory.FOOD_ACCESS
   */
  @Column({ type: 'enum', enum: TagCategory, enumName: 'tag_category' })
  category!: TagCategory;

  /**
   * ID of the TagGroup this Tag belongs to.
   *
   * E.g. 1, 2, 3
   */
  @Column({ type: 'int' })
  group_id!: number;

  @ManyToOne(() => TagGroup, { nullable: false })
  @JoinColumn({
    name: 'group_id',
    foreignKeyConstraintName: 'FK_tags_group_id',
  })
  group?: TagGroup;

  /**
   * The human-readable name of the Tag, used for display.
   *
   * E.g. 'Food pantry', 'Proof of address', 'Other'
   */
  @Column({ type: 'varchar', length: 255 })
  label!: string;

  /**
   * A URL-friendly version of the label. Unique within its group.
   *
   * E.g. 'food-pantry', 'proof-of-address', 'other-letter-from-landlord'
   */
  @Column({ type: 'varchar', length: 255 })
  slug!: string;

  /**
   * The position of the Tag within its group when listed.
   *
   * E.g. 0, 1, 2
   */
  @Column({ type: 'int', default: 0 })
  sort_order!: number;

  /**
   * Whether the Tag can still be attached to resources. Tags are deactivated instead of deleted
   * so that IDs stored in Resource.tags never dangle.
   */
  @Column({ type: 'boolean', default: true })
  is_active!: boolean;

  /**
   * True on the seeded "Other" tag of a group. It is a template: when a user types custom text,
   * a new custom Tag is created from it.
   */
  @Column({ type: 'boolean', default: false })
  allows_free_text!: boolean;

  /**
   * True on Tags created from user-typed "Other" text, false on seeded Tags.
   */
  @Column({ type: 'boolean', default: false })
  is_custom!: boolean;

  /**
   * The text the user typed for a custom Tag. Set exactly when is_custom is true.
   *
   * E.g. 'Letter from landlord'
   */
  @Column({ type: 'text', nullable: true })
  other_text?: string | null;
}

